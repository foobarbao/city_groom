/**
 * @file State of the partner spaces: merchant conversations and quotes,
 * replies to reviews, service settings, items marked ready, courier stops
 * done.
 *
 * DEMO: there is no partner API yet. The state lives on the device
 * (`localStorage`, wrapped in try/catch), conversations start from a few
 * fictitious customer requests and customer answers are simulated; the app
 * labels them as such.
 * PROD: merchant and courier endpoints of the API (conversations, quotes,
 * reviews, offers, round progress).
 */
import { reactive, watch } from 'vue'

/** A quote sent by the merchant in a conversation. */
export interface MerchantQuote {
  label: string
  priceCents: number
  size: string
  status: 'sent' | 'accepted' | 'declined'
}

/** One message of a conversation with a customer. */
export interface ThreadMessage {
  from: 'customer' | 'merchant'
  text: string
  at: string
  quote: MerchantQuote | null
  /** True for customer messages generated by the demo. */
  simulated: boolean
}

/** A conversation with one customer. */
export interface Thread {
  id: string
  customer: string
  messages: ThreadMessage[]
}

interface PartnerState {
  threads: Record<string, Thread[]>
  reviewReplies: Record<string, Record<string, string>>
  ready: string[]
  stopsDone: Record<string, string[]>
  /** Planning tasks marked done (absent in states saved before the planning). */
  tasksDone?: string[]
  /** Webhook address entered per merchant (DEMO: stored, nothing is sent). */
  webhooks?: Record<string, string>
}

const STORAGE_KEY = 'citypal-partner-demo-v1'
/** Delay of simulated customer answers. */
const ANSWER_DELAY_MS = 2000

/** First request of a fictitious customer, by service category (demo seed). */
const FIRST_REQUESTS: Record<string, string> = {
  dry_cleaning: 'Bonjour, pouvez-vous nettoyer une robe en soie avec une petite tache ?',
  laundry: 'Bonjour, prenez-vous les couettes 2 places ?',
  tailoring: 'Bonjour, j’aurais besoin de raccourcir un pantalon de 3 cm.',
  shoe_repair: 'Bonjour, le talon de mes bottes est usé, est-ce réparable ?',
  watch_repair: 'Bonjour, le verre de ma montre est rayé, pouvez-vous le changer ?',
  jewellery_repair: 'Bonjour, le fermoir de mon collier est cassé.',
  electronics_repair: 'Bonjour, la batterie de mon téléphone ne tient plus la journée.',
  key_cutting: 'Bonjour, il me faudrait 3 doubles de clés de boîte aux lettres.',
}

function load(): PartnerState | null {
  try {
    const raw = localStorage.getItem(STORAGE_KEY)
    return raw ? (JSON.parse(raw) as PartnerState) : null
  } catch {
    return null // storage unavailable (private mode, blocked site data)
  }
}

const empty = (): PartnerState => ({
  threads: {},
  reviewReplies: {},
  ready: [],
  stopsDone: {},
  tasksDone: [],
  webhooks: {},
})

export const partnerState = reactive<PartnerState>(load() ?? empty())

watch(
  partnerState,
  (value) => {
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(value))
    } catch {
      // Storage full or unavailable: the demo keeps working in memory.
    }
  },
  { deep: true },
)

/** Creates the fictitious conversations of a merchant, once (call from a watcher). */
export function seedThreads(merchant: string, category: string, now: Date = new Date()): void {
  if (!partnerState.threads[merchant]) {
    const ago = (hours: number): string => new Date(now.getTime() - hours * 3600e3).toISOString()
    partnerState.threads[merchant] = [
      {
        id: `${merchant}-1`,
        customer: 'Camille R.',
        messages: [
          {
            from: 'customer',
            text: FIRST_REQUESTS[category] ?? 'Bonjour, pouvez-vous me faire un devis ?',
            at: ago(2),
            quote: null,
            simulated: true,
          },
        ],
      },
      {
        id: `${merchant}-2`,
        customer: 'Hugo M.',
        messages: [
          {
            from: 'customer',
            text: 'Bonjour, quels sont vos délais en ce moment ?',
            at: ago(26),
            quote: null,
            simulated: true,
          },
          {
            from: 'merchant',
            text: 'Bonjour, comptez une journée pour la plupart des prestations.',
            at: ago(25),
            quote: null,
            simulated: true,
          },
        ],
      },
    ]
  }
}

/** Conversations of a merchant (empty until seeded). */
export const threadsOf = (merchant: string): Thread[] => partnerState.threads[merchant] ?? []

/** Whether a conversation waits for the merchant's answer. */
export const awaitsAnswer = (thread: Thread): boolean =>
  thread.messages[thread.messages.length - 1]?.from === 'customer'

/**
 * Sends a message, optionally with a quote. DEMO: the customer accepts the
 * quote after a short delay (simulated answer).
 */
export function reply(
  thread: Thread,
  text: string,
  quote: Omit<MerchantQuote, 'status'> | null,
): void {
  const message: ThreadMessage = {
    from: 'merchant',
    text,
    at: new Date().toISOString(),
    quote: quote ? { ...quote, status: 'sent' } : null,
    simulated: false,
  }
  thread.messages.push(message)
  if (!quote) return
  setTimeout(() => {
    const sent = thread.messages.find((m) => m.at === message.at && m.quote)
    if (sent?.quote) sent.quote.status = 'accepted'
    thread.messages.push({
      from: 'customer',
      text: 'Parfait, j’accepte le devis. Je dépose l’article au casier.',
      at: new Date().toISOString(),
      quote: null,
      simulated: true,
    })
  }, ANSWER_DELAY_MS)
}

/** Marks an order ready to go back at the next round (or undoes it). */
export function toggleReady(orderId: string): void {
  const index = partnerState.ready.indexOf(orderId)
  if (index === -1) partnerState.ready.push(orderId)
  else partnerState.ready.splice(index, 1)
}

/** Whether a planning task is done. */
export const isTaskDone = (id: string): boolean => (partnerState.tasksDone ?? []).includes(id)

/**
 * Marks a planning task done (or undoes it). A handover done also marks its
 * items ready for the courier, as on the rounds screen.
 */
export function toggleTask(id: string, handoverOrders: string[] = []): void {
  const done = (partnerState.tasksDone ??= [])
  const index = done.indexOf(id)
  if (index === -1) {
    done.push(id)
    for (const orderId of handoverOrders)
      if (!partnerState.ready.includes(orderId)) partnerState.ready.push(orderId)
  } else done.splice(index, 1)
}

/** Webhook address of a merchant's automation, if entered. */
export const webhookOf = (merchant: string): string => partnerState.webhooks?.[merchant] ?? ''

/** Saves (or clears, with an empty string) a merchant's webhook address. */
export function setWebhook(merchant: string, url: string): void {
  const hooks = (partnerState.webhooks ??= {})
  if (url) hooks[merchant] = url
  else delete hooks[merchant]
}

/** Marks a stop of a round as done (or undoes it). */
export function toggleStop(roundId: string, stopKey: string): void {
  const done = (partnerState.stopsDone[roundId] ??= [])
  const index = done.indexOf(stopKey)
  if (index === -1) done.push(stopKey)
  else done.splice(index, 1)
}

/** Back to the fictitious starting state. */
export function resetPartnerDemo(): void {
  Object.assign(partnerState, empty())
}

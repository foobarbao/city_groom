/**
 * @file State of the customer: profile, subscription, consigne bookings,
 * orders, conversations with merchants, quotes and reviews.
 *
 * DEMO: there is no customer API yet. The state lives on the device
 * (`localStorage`, wrapped in try/catch: it may be unavailable), starts from
 * a few fictitious items so every screen has something to show, and merchant
 * replies are simulated. Everything is labelled as a demo in the app.
 * PROD: replace with the customer endpoints of the API (accounts, bookings,
 * orders, conversations, quotes, reviews — ADR-0008).
 */
import { defineStore } from 'pinia'
import { computed, ref, watch } from 'vue'

import { addHours, serviceDay } from '../domain/time'

/** Status of a service order, as in the demo activity. */
export type OrderStatus =
  'awaiting_drop_off' | 'in_locker' | 'at_merchant' | 'ready_for_pickup' | 'picked_up'

/** A service ordered from a partner shop. */
export interface CustomerOrder {
  id: string
  shopCode: string
  /** What was ordered: service name, or quote label. */
  label: string
  quantity: number
  priceCents: number
  size: string
  dropLocker: string
  pickupLocker: string
  createdAt: string
  status: OrderStatus
}

/** A consigne booking. */
export interface ConsigneBooking {
  id: string
  lockerCode: string
  size: string
  /** Immediate drop-off, or a booked slot. */
  mode: 'now' | 'slot'
  slotCode: string | null
  slotStart: string
  slotEnd: string
  door: string
  priceCents: number
  bookedAt: string
  droppedAt: string | null
  /** Pickup slot chosen by the customer (absent on older bookings: 24 hours). */
  pickupStart?: string | null
  pickupEnd?: string | null
  status: 'booked' | 'stored' | 'collected' | 'cancelled'
  /** Move to another locker at a round (absent on bookings saved before transfers existed). */
  transfer?: ConsigneTransfer | null
}

/** Stored items moved to another locker by a courier at a round. */
export interface ConsigneTransfer {
  toLocker: string
  /** Round at which the items are moved; collectable at the new locker after it. */
  roundAt: string
  door: string
  priceCents: number
  /** True when covered by the plan's monthly allowance. */
  included: boolean
  requestedAt: string
}

/** A quote sent by a merchant for a special service. */
export interface Quote {
  id: string
  shopCode: string
  label: string
  priceCents: number
  size: string
  status: 'pending' | 'accepted' | 'declined'
  at: string
}

/** One message of a conversation. */
export interface ChatMessage {
  id: string
  from: 'customer' | 'merchant'
  text: string
  at: string
  /** Downscaled photo as a data URL. */
  photo: string | null
  quoteId: string | null
  /** True for replies generated by the demo. */
  simulated: boolean
}

/** A review written by the customer (one per order, ADR-0008). */
export interface MyReview {
  orderId: string
  shopCode: string
  rating: number
  comment: string
  at: string
}

interface AccountState {
  signedIn: boolean
  name: string
  plan: string
  bookings: ConsigneBooking[]
  orders: CustomerOrder[]
  conversations: Record<string, ChatMessage[]>
  quotes: Quote[]
  reviews: MyReview[]
}

const STORAGE_KEY = 'citypal-demo-v1'
/** Delay of simulated merchant replies, so they feel like a real exchange. */
const REPLY_DELAY_MS = 1500

let counter = 0
const newId = (prefix: string): string =>
  `${prefix}-${Date.now().toString(36)}${(counter++).toString(36)}`


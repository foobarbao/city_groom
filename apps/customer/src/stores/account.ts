function load(): AccountState | null {
  try {
    const raw = localStorage.getItem(STORAGE_KEY)
    return raw ? (JSON.parse(raw) as AccountState) : null
  } catch {
    return null // storage unavailable (private mode, blocked site data)
  }
}

function save(state: AccountState): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(state))
  } catch {
    // Storage full or unavailable: the demo keeps working in memory.
  }
}

export const useAccountStore = defineStore('account', () => {
  const state = ref<AccountState>(load() ?? demoSeed(new Date()))
  watch(state, (value) => save(value), { deep: true })

  const reviewedOrderIds = computed(() => new Set(state.value.reviews.map((r) => r.orderId)))
  const activeBookings = computed(() =>
    state.value.bookings.filter((b) => b.status === 'booked' || b.status === 'stored'),
  )
  const pendingQuotes = computed(() => state.value.quotes.filter((q) => q.status === 'pending'))
  /** Included transfers already used this calendar month (Grenoble time). */
  const transfersUsedThisMonth = computed(() => {
    const month = serviceDay(new Date()).slice(0, 7)
    return state.value.bookings.filter(
      (b) => b.transfer?.included && serviceDay(new Date(b.transfer.requestedAt)).startsWith(month),
    ).length
  })

  /** Demo sign-in: no password, the name is only shown in the app. */
  function signIn(name: string): void {
    state.value.signedIn = true
    state.value.name = name.trim() || 'Camille'
  }

  /** Real sign-in with Google: the API has verified the Google token (ADR-0010). */
  function signInWithGoogle(result: SignInResponse): void {
    state.value.signedIn = true
    state.value.name = result.user.first_name || result.user.email
    state.value.google = {
      email: result.user.email,
      pictureUrl: result.user.picture_url,
      token: result.token,
    }
  }

  function signOut(): void {
    const token = state.value.google?.token
    if (token) {
      // Best effort: the local session ends even if the server is unreachable.
      signOutFromApi(token).catch(() => undefined)
      forgetGoogleSession()
    }
    state.value.signedIn = false
    state.value.google = null
    state.value.plan = 'free'
  }

  /** Demo subscription: no payment. Requires being signed in. */
  function choosePlan(code: string): void {
    if (state.value.signedIn) state.value.plan = code
  }

  function addBooking(booking: Omit<ConsigneBooking, 'id' | 'bookedAt' | 'status'>): string {
    const id = newId('B')
    state.value.bookings.unshift({
      ...booking,
      id,
      bookedAt: new Date().toISOString(),
      status: 'booked',
    })
    return id
  }

  /** The customer dropped the item (the door was opened in the demo). */
  function markDropped(id: string): void {
    const booking = state.value.bookings.find((b) => b.id === id)
    if (booking?.status === 'booked') {
      booking.status = 'stored'
      booking.droppedAt = new Date().toISOString()
    }
  }

  function markCollected(id: string): void {
    const booking = state.value.bookings.find((b) => b.id === id)
    if (booking?.status === 'stored') booking.status = 'collected'
  }

  /** Asks a courier to move the items to another locker (one transfer per booking in the demo). */
  function requestTransfer(id: string, transfer: Omit<ConsigneTransfer, 'requestedAt'>): void {
    const booking = state.value.bookings.find((b) => b.id === id)
    if (
      !booking ||
      booking.transfer ||
      (booking.status !== 'booked' && booking.status !== 'stored')
    )
      return
    booking.transfer = { ...transfer, requestedAt: new Date().toISOString() }
  }

  function cancelBooking(id: string): void {
    const booking = state.value.bookings.find((b) => b.id === id)
    if (booking?.status === 'booked') booking.status = 'cancelled'
  }

  function addOrder(order: Omit<CustomerOrder, 'id' | 'createdAt' | 'status'>): string {
    const id = newId('C')
    state.value.orders.unshift({
      ...order,
      id,
      createdAt: new Date().toISOString(),
      status: 'awaiting_drop_off',
    })
    return id
  }

  /** Whether the customer already bought a given pack (welcome offer used). */
  function hasBoughtPack(code: string): boolean {
    return (state.value.packs ?? []).some((p) => p.packCode === code)
  }

  /**
   * Buys four weeks of a pack in one order: one purchase, and one order per
   * week to drop off and collect. DEMO: payment simulated.
   */
  function buyPack(
    purchase: Omit<PackPurchase, 'id' | 'boughtAt' | 'orderIds'>,
    weeks: {
      week: number
      dropFrom: Date
      dropBy: Date
      returnAt: Date
      pickupStart?: Date
      pickupEnd?: Date
    }[],
    order: { label: string; quantity: number; size: string; shopCode: string; door?: string },
  ): string {
    const id = newId('P')
    const now = new Date().toISOString()
    const created: CustomerOrder[] = weeks.map((w) => ({
      id: newId('C'),
      shopCode: order.shopCode,
      label: `${order.label} · semaine ${w.week}/${weeks.length}`,
      quantity: order.quantity,
      priceCents: purchase.weeklyCents,
      size: order.size,
      dropLocker: purchase.dropLocker,
      pickupLocker: purchase.pickupLocker,
      createdAt: now,
      status: 'awaiting_drop_off',
      door: order.door,
      packId: id,
      packWeek: w.week,
      dropFrom: w.dropFrom.toISOString(),
      dropBy: w.dropBy.toISOString(),
      returnAt: w.returnAt.toISOString(),
      readyAt: w.returnAt.toISOString(),
      pickupStart: w.pickupStart?.toISOString(),
      pickupEnd: w.pickupEnd?.toISOString(),
    }))
    // Week 1 first in the order list.
    state.value.orders.unshift(...created)
    const orderIds = created.map((o) => o.id)
    ;(state.value.packs ??= []).unshift({ ...purchase, id, boughtAt: now, orderIds })
    return id
  }

  function markOrderDropped(id: string): void {
    const order = state.value.orders.find((o) => o.id === id)
    if (order?.status !== 'awaiting_drop_off') return
    order.status = 'in_locker'
    order.droppedAt = new Date().toISOString()
  }

  function addReview(review: Omit<MyReview, 'at'>): void {
    if (reviewedOrderIds.value.has(review.orderId)) return
    state.value.reviews.push({ ...review, at: new Date().toISOString() })
  }

  function setQuoteStatus(id: string, status: Quote['status']): void {
    const quote = state.value.quotes.find((q) => q.id === id)
    if (quote?.status === 'pending') quote.status = status
  }

  /**
   * Sends a message to a merchant. DEMO: the merchant answers automatically;
   * a photo or a question about a price gets a fictitious quote.
   */
  function sendMessage(shopCode: string, text: string, photo: string | null): void {
    const messages = (state.value.conversations[shopCode] ??= [])
    messages.push({
      id: newId('M'),
      from: 'customer',
      text,
      at: new Date().toISOString(),
      photo,
      quoteId: null,
      simulated: false,
    })
    const wantsQuote = photo !== null || /devis|prix|combien|tarif/i.test(text)
    setTimeout(() => {
      let quoteId: string | null = null
      if (wantsQuote) {
        quoteId = newId('Q')
        state.value.quotes.unshift({
          id: quoteId,
          shopCode,
          label: photo ? 'Prestation sur photo' : 'Prestation sur devis',
          // Fictitious amount between 15 and 45 euros.
          priceCents: 1500 + ((text.length * 137) % 31) * 100,
          size: 'L',
          status: 'pending',
          at: new Date().toISOString(),
        })
      }
      state.value.conversations[shopCode]?.push({
        id: newId('M'),
        from: 'merchant',
        text: wantsQuote
          ? 'Merci ! Voici notre devis. Vous pouvez l’accepter ici.'
          : 'Merci pour votre message, nous vous répondons très vite.',
        at: new Date().toISOString(),
        photo: null,
        quoteId,
        simulated: true,
      })
    }, REPLY_DELAY_MS)
  }

  /** Back to the fictitious starting state. */
  function resetDemo(): void {
    state.value = demoSeed(new Date())
  }

  return {
    state,
    reviewedOrderIds,
    activeBookings,
    pendingQuotes,
    transfersUsedThisMonth,
    signIn,
    signInWithGoogle,
    signOut,
    choosePlan,
    addBooking,
    markDropped,
    markCollected,
    cancelBooking,
    requestTransfer,
    addOrder,
    markOrderDropped,
    hasBoughtPack,
    buyPack,
    addReview,
    setQuoteStatus,
    sendMessage,
    resetDemo,
  }
})
